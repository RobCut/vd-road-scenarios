classdef TestComposeAllPatterns < matlab.unittest.TestCase
    %TestComposeAllPatterns Verify that compose dispatches to every
    %   pattern in the catalog with a minimal valid segment.

    properties (TestParameter)
        Segment = struct( ...
            'iso8608',      struct('Type', "iso8608",      'Params', {{'B'}}), ...
            'sine',         struct('Type', "sine",         'Params', {{0.5, 0.01}}), ...
            'washboard',    struct('Type', "washboard",    'Params', {{0.02, 0.5}}), ...
            'belgianBlock', struct('Type', "belgianBlock", 'Params', {{0.03, 0.2}}), ...
            'cobblestone',  struct('Type', "cobblestone",  'Params', {{0.02, 0.1}}), ...
            'bump',         struct('Type', "bump",         'Params', {{0.10, 0.6, 0}}), ...
            'pothole',      struct('Type', "pothole",      'Params', {{0.05, 0.6, 0}}), ...
            'crest',        struct('Type', "crest",        'Params', {{0.05, 0.6, 0}}), ...
            'valley',       struct('Type', "valley",       'Params', {{0.05, 0.6, 0}}), ...
            'edge',         struct('Type', "edge",         'Params', {{0.05, 2, 4}}), ...
            'step',         struct('Type', "step",         'Params', {{0.05, 2}}), ...
            'kink',         struct('Type', "kink",         'Params', {{2, 0.01, -0.01}}), ...
            'chirp',        struct('Type', "chirp",        'Params', {{0.5, 2.0, 0.01}}), ...
            'multiSine',    struct('Type', "multiSine",    'Params', {{[1, 2], [0.01, 0.005]}}), ...
            'flat',         struct('Type', "flat",         'Params', {{0.02}}))
    end

    methods (Test)
        function test_compose_dispatches(testCase, Segment)
            %test_compose_dispatches Verify that compose can dispatch
            %   to every catalog pattern without error.
            L = 10; dx = 0.01;
            segs = struct( ...
                'Start', 2, ...
                'Stop', 8, ...
                'Type', Segment.Type, ...
                'Params', {Segment.Params});
            p = roadprofile.compose(L, dx, segs, Seed=42);
            testCase.verifyEqual(numel(p.z), round(L/dx));
            testCase.verifyTrue(all(isfinite(p.z)));
        end
    end
end