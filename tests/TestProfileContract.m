classdef TestProfileContract < matlab.unittest.TestCase
    %TestProfileContract Verify the common profile structure (§6 DESIGN).
    %   Every pattern must return a struct with fields x, z, dx, column
    %   vectors of the same length, x starting at 0, and finite z.

    properties (TestParameter)
        Pattern = struct( ...
            'sine',         @() roadprofile.sine(20, 0.01, 2.0, 0.02), ...
            'iso8608',      @() roadprofile.iso8608Profile(20, 0.01, 'B', Seed=1), ...
            'washboard',    @() roadprofile.washboard(20, 0.01, 0.02, 0.5), ...
            'belgianBlock', @() roadprofile.belgianBlock(20, 0.01, 0.03, 0.2, Seed=1), ...
            'cobblestone',  @() roadprofile.cobblestone(20, 0.01, 0.02, 0.1, Seed=1), ...
            'bump',         @() roadprofile.bump(20, 0.01, 0.10, 0.6, 10), ...
            'pothole',      @() roadprofile.pothole(20, 0.01, 0.05, 0.6, 10), ...
            'crest',        @() roadprofile.crest(20, 0.01, 0.05, 0.6, 10), ...
            'valley',       @() roadprofile.valley(20, 0.01, 0.05, 0.6, 10), ...
            'edge',         @() roadprofile.edge(20, 0.01, 0.05, 8, 12), ...
            'step',         @() roadprofile.step(20, 0.01, 0.05, 10), ...
            'kink',         @() roadprofile.kink(20, 0.01, 10, 0.01, -0.01), ...
            'chirp',        @() roadprofile.chirp(20, 0.01, 0.5, 5.0, 0.01), ...
            'multiSine',    @() roadprofile.multiSine(20, 0.01, [1, 2.5], [0.01, 0.005]), ...
            'flat',         @() roadprofile.flat(20, 0.01))
    end

    methods (Test)
        function test_structure(testCase, Pattern)
            %test_structure Verify the fields, shapes, and origin that
            %   every pattern must respect (DESIGN §6).
            p = Pattern();
            testCase.verifyTrue(isstruct(p) && isscalar(p));
            testCase.verifyTrue(isfield(p, 'x'));
            testCase.verifyTrue(isfield(p, 'z'));
            testCase.verifyTrue(isfield(p, 'dx'));
            testCase.verifySize(p.x, [numel(p.x), 1]);
            testCase.verifySize(p.z, [numel(p.z), 1]);
            testCase.verifyEqual(numel(p.x), numel(p.z));
            testCase.verifyEqual(p.x(1), 0, 'AbsTol', 1e-12);
            testCase.verifyEqual(p.x(end), (numel(p.x)-1) * p.dx, 'AbsTol', 1e-12);
            testCase.verifyTrue(all(isfinite(p.z)));
        end
    end
end