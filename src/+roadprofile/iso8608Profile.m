function p = iso8608Profile(L, dx, roadClass, options)
%ISO8608PROFILE Generate a 1D road profile from the ISO 8608 PSD.
%   P = ISO8608PROFILE(L, DX, CLASS) returns a struct P with fields x, z,
%   dx, containing a synthetic road profile of length L (in metres) sampled
%   at spatial resolution DX (in metres), for the given roughness CLASS
%   ('A' to 'H').
%
%   P = ISO8608PROFILE(..., Seed=S) uses the random seed S for
%   deterministic generation. Two calls with the same seed produce
%   identical profiles.
%
%   P = ISO8608PROFILE(..., NMin=N1, NMax=N2) limits the spectrum to
%   [N1, N2] cycles/m (default 0.011 to 2.83). NMin=0, NMax=Inf gives
%   the full spectrum up to Nyquist (Nyquist bin excluded).
%
%   The profile is generated by IFFT of a one-sided PSD with random phases,
%   following the ISO 8608 model G_d(n) = G0 * (n/n0)^-2. The resulting
%   profile is mean-zero.
%
%   See also roadprofile.iso8608PSD.

arguments
    L (1,1) {mustBeNumeric, mustBeFinite, mustBePositive}
    dx (1,1) {mustBeNumeric, mustBeFinite, mustBePositive}
    roadClass {mustBeTextScalar}
    options.Seed {mustBeNumeric, mustBeInteger, mustBeNonnegative, mustBeScalarOrEmpty} = []
    options.NMin (1,1) double {mustBeFinite, mustBeNonnegative} = 0.011
    options.NMax (1,1) double {mustBePositive} = 2.83   % Inf = up to Nyquist
end

if ~isempty(options.Seed)
    previousState = rng;
    rng(options.Seed, 'twister');
    cleanup = onCleanup(@() rng(previousState)); %#ok<NASGU>
end
[x, N] = roadprofile.internal.sampleGrid(L, dx, 4);
Leff = N * dx;
dn = 1 / Leff;
k = (1:ceil(N/2)-1)';      % excludes DC and Nyquist
n = k * dn;
inBand = n >= options.NMin & n <= options.NMax;
if ~any(inBand)
    error('roadprofile:emptyBand', ...
        'No spectral line in [%g, %g] cycles/m (resolution %g)', ...
        options.NMin, options.NMax, dn);
end
G = roadprofile.iso8608PSD(roadClass, n(inBand));
z = roadprofile.internal.spectralSynthesis(N, k(inBand), sqrt(G * dn / 2));
p.x = x;
p.z = z;
p.dx = dx;
end